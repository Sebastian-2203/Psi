-- =============================================================================
-- Workstream 1.3 (authentication): MFA recovery codes (ADR-021) and staff invitation
-- preview (SECURITY.md §3.8). Forward-only.
--
-- * Recovery codes are hashed with bcrypt (pgcrypto `crypt`/`gen_salt('bf')`), compared in
--   the database, single use, batch-revoked on regeneration. Raw codes are never stored.
--   Native GoTrue recovery codes (auth.mfa_recovery_code_sets, behind a flag) are NOT used:
--   ADR-021 stays app-managed until the architect/security supersede it.
-- * Every function: set search_path = '', identity only from auth.uid()/auth.jwt(), no
--   dynamic SQL, execute revoked from public/anon/service_role.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- app.has_recent_mfa(seconds): aal2 AND a TOTP verification in the verified `amr` claim
-- within the window (SECURITY.md §3.2 point 3; API_CONTRACTS §4 mfaVerifiedAt).
-- -----------------------------------------------------------------------------
create function app.has_recent_mfa(p_seconds integer) returns boolean
language sql
stable
set search_path = ''
as $$
  select (select app.is_aal2()) and coalesce((
    select bool_or(
      e ->> 'method' in ('totp', 'mfa/totp')
      and (e ->> 'timestamp') ~ '^\d{1,12}$'
      and (e ->> 'timestamp')::bigint >= extract(epoch from now())::bigint - p_seconds
    )
    from jsonb_array_elements(
      case when jsonb_typeof((select auth.jwt()) -> 'amr') = 'array'
           then (select auth.jwt()) -> 'amr' else '[]'::jsonb end
    ) as e
  ), false)
$$;
comment on function app.has_recent_mfa(integer) is
  'aal2 AND last TOTP verification (amr claim) within p_seconds. For high-risk actions.';
revoke all on function app.has_recent_mfa(integer) from public, anon, service_role;
grant execute on function app.has_recent_mfa(integer) to authenticated;

-- -----------------------------------------------------------------------------
-- app.replace_recovery_codes(codes): caller-only, aal2 + MFA within 15 min. Revokes the
-- previous unused codes and stores exactly 10 new bcrypt hashes. Returns the batch id.
-- Codes are generated by the server (CSPRNG, 16 chars of a 32-symbol alphabet = 80 bits).
-- -----------------------------------------------------------------------------
create function app.replace_recovery_codes(p_codes text[]) returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_batch uuid := gen_random_uuid();
  v_code text;
begin
  if v_actor is null then
    raise exception using errcode = 'P0001', message = 'PRECONDITION:no_actor';
  end if;
  if not app.has_recent_mfa(900) then
    raise exception using errcode = 'P0001', message = 'PRECONDITION:recent_mfa_required';
  end if;
  if p_codes is null or cardinality(p_codes) <> 10
     or (select count(distinct c) from unnest(p_codes) c) <> 10 then
    raise exception using errcode = 'P0001', message = 'PRECONDITION:recovery_codes_invalid';
  end if;
  foreach v_code in array p_codes loop
    if v_code !~ '^[A-HJ-NP-Z2-9]{16}$' then
      raise exception using errcode = 'P0001', message = 'PRECONDITION:recovery_codes_invalid';
    end if;
  end loop;

  update public.mfa_recovery_codes
     set revoked_at = now()
   where profile_id = v_actor and used_at is null and revoked_at is null;

  insert into public.mfa_recovery_codes (profile_id, batch_id, code_hash)
  select v_actor, v_batch, extensions.crypt(c, extensions.gen_salt('bf', 10))
  from unnest(p_codes) as c;

  perform app.write_audit('auth.recovery_codes_generated', null, 'mfa_recovery_batch', v_batch,
                          jsonb_build_object('batch_id', v_batch), null);
  return v_batch;
end
$$;
comment on function app.replace_recovery_codes(text[]) is
  'ADR-021: caller replaces own recovery codes (aal2 + recent MFA); stores bcrypt hashes only; audited.';
revoke all on function app.replace_recovery_codes(text[]) from public, anon, service_role;
grant execute on function app.replace_recovery_codes(text[]) to authenticated;

-- -----------------------------------------------------------------------------
-- app.consume_recovery_code(code): caller-only (any aal: the password was verified).
-- Rate limited per profile, FAIL CLOSED (ADR-020): 5 attempts / 15 min. On success marks
-- the code used (single use) and writes auth.recovery_code_used; failures write
-- auth.mfa_failed; limiter hits write auth.rate_limited. The factor reset itself is done by
-- the server through the Auth admin API afterwards (src/server/db/admin.ts).
-- -----------------------------------------------------------------------------
create function app.consume_recovery_code(p_code text)
returns table (status text, batch_id uuid)
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_actor uuid := (select auth.uid());
  v_code text := upper(regexp_replace(coalesce(p_code, ''), '[\s-]', '', 'g'));
  v_row record;
begin
  if v_actor is null then
    raise exception using errcode = 'P0001', message = 'PRECONDITION:no_actor';
  end if;

  if not app.consume_rate_limit('auth.recovery_code', 5, interval '15 minutes') then
    perform app.insert_audit_row('auth.rate_limited', 'system', 'system', v_actor, '{}', null,
      null, null, jsonb_build_object('action', 'auth.recovery_code'), null, null, null);
    status := 'rate_limited';
    return next;
    return;
  end if;

  if v_code ~ '^[A-HJ-NP-Z2-9]{16}$' then
    for v_row in
      select c.id, c.batch_id, c.code_hash
      from public.mfa_recovery_codes c
      where c.profile_id = v_actor and c.used_at is null and c.revoked_at is null
      for update
    loop
      if extensions.crypt(v_code, v_row.code_hash) = v_row.code_hash then
        update public.mfa_recovery_codes set used_at = now() where id = v_row.id;
        perform app.insert_audit_row('auth.recovery_code_used', 'system', 'system', v_actor, '{}',
          null, 'mfa_recovery_batch', v_row.batch_id,
          jsonb_build_object('batch_id', v_row.batch_id), null, null, null);
        status := 'ok';
        batch_id := v_row.batch_id;
        return next;
        return;
      end if;
    end loop;
  end if;

  perform app.insert_audit_row('auth.mfa_failed', 'system', 'system', v_actor, '{}', null,
    null, null, '{}'::jsonb, null, null, null);
  status := 'invalid';
  return next;
end
$$;
comment on function app.consume_recovery_code(text) is
  'ADR-021: caller consumes one own recovery code (bcrypt compare, single use, rate limited fail-closed, audited).';
revoke all on function app.consume_recovery_code(text) from public, anon, service_role;
grant execute on function app.consume_recovery_code(text) to authenticated;

-- -----------------------------------------------------------------------------
-- app.my_recovery_codes_status(): remaining unused codes of the caller's active batch.
-- -----------------------------------------------------------------------------
create function app.my_recovery_codes_status()
returns table (batch_id uuid, remaining integer, total integer, created_at timestamptz)
language sql
stable
security definer
set search_path = ''
as $$
  select c.batch_id,
         (count(*) filter (where c.used_at is null))::integer,
         count(*)::integer,
         min(c.created_at)
  from public.mfa_recovery_codes c
  where c.profile_id = (select auth.uid()) and c.revoked_at is null
  group by c.batch_id
  order by min(c.created_at) desc
  limit 1
$$;
revoke all on function app.my_recovery_codes_status() from public, anon, service_role;
grant execute on function app.my_recovery_codes_status() to authenticated;

-- -----------------------------------------------------------------------------
-- app.peek_staff_invitation(token_hash): SYSTEM PATH (app_server, no user claims).
-- Returns the pending, unexpired staff invitation for sha256(token) in an active org, plus
-- the id of an existing auth user with the same email (server-internal: used to decide
-- between "create user" and "verify existing password"; never sent to the browser).
-- -----------------------------------------------------------------------------
create function app.peek_staff_invitation(p_token_hash bytea)
returns table (
  invitation_id uuid,
  organization_id uuid,
  organization_display_name text,
  email text,
  roles public.membership_role[],
  expires_at timestamptz,
  existing_profile_id uuid
)
language plpgsql
stable
security definer
set search_path = ''
as $$
#variable_conflict use_column
begin
  if (select auth.uid()) is not null then
    raise exception using errcode = 'P0001', message = 'PRECONDITION:system_function_in_user_context';
  end if;
  if p_token_hash is null or octet_length(p_token_hash) <> 32 then
    return;
  end if;
  return query
  select i.id, i.organization_id, o.display_name, i.email::text, i.roles, i.expires_at,
         (select u.id from auth.users u
           where lower(u.email) = lower(i.email::text) and u.deleted_at is null
           limit 1)
  from public.invitations i
  join public.organizations o on o.id = i.organization_id
  where i.token_hash = p_token_hash
    and i.status = 'pending'
    and i.expires_at > now()
    and i.invitation_type = 'staff'
    and o.status = 'active';
end
$$;
comment on function app.peek_staff_invitation(bytea) is
  'System path: read a pending staff invitation by sha256(token) before acceptance (no state change).';
revoke all on function app.peek_staff_invitation(bytea) from public, anon, authenticated, service_role;
grant execute on function app.peek_staff_invitation(bytea) to app_server;
